    slack = Slack()
    ts = slack.post_rca(
        title="🚨 PodCrashLooping — helloworld/helloworld-deployment-xxx",
        summary="Container is restarting repeatedly (CrashLoopBackOff)",
        fields={
            "Namespace": "helloworld",
            "Pod": "helloworld-deployment-85dfb4cf8f-vxn9l",
            "Container": "helloworld-container",
            "Severity": "critical",
            "Restarts": "108",
        },
        rca_body=(
            "*Root cause (stub)*\n"
            "This is a test message from the SRE agent. Real RCA will be "
            "generated by Claude in the next step.\n\n"
            "*Suggested fix*\n"
            "• Check that the container's readiness/liveness probe ports "
            "match the port the app actually listens on."
        ),
    )
    print(f"Posted message ts={ts}")
